import os
from typing import Dict, Any


class OllamaExporter:
    """
    Generates Ollama Modelfile and local serving scripts for quantized GGUF models.
    """

    @staticmethod
    def generate_modelfile(
        model_name: str,
        system_prompt: str = "You are a specialized expert assistant trained for this task.",
        temperature: float = 0.7,
        top_p: float = 0.9,
        context_window: int = 4096,
        gguf_filename: str = ""
    ) -> str:
        """Generates an Ollama Modelfile specification."""
        gguf_ref = gguf_filename if gguf_filename else f"./{model_name}.gguf"

        modelfile = f"""# Modelfile generated by AI Model Trainer Studio
FROM {gguf_ref}

# Inference Hyperparameters
PARAMETER temperature {temperature}
PARAMETER top_p {top_p}
PARAMETER num_ctx {context_window}
PARAMETER stop "<|eot_id|>"
PARAMETER stop "<|end_of_text|>"

# System Persona
SYSTEM \"\"\"{system_prompt}\"\"\"

# Template
TEMPLATE \"\"\"{{{{ if .System }}}}<|start_header_id|>system<|end_header_id|>

{{{{ .System }}}}<|eot_id|>{{{{ end }}}}{{{{ if .Prompt }}}}<|start_header_id|>user<|end_header_id|>

{{{{ .Prompt }}}}<|eot_id|>{{{{ end }}}}<|start_header_id|>assistant<|end_header_id|>

{{{{ .Response }}}}<|eot_id|>\"\"\"
"""
        return modelfile

    @staticmethod
    def generate_local_deploy_script(model_name: str) -> str:
        """Generates a simple batch/bash script to register the model into Ollama."""
        return f"""@echo off
echo ==============================================
echo Registering {model_name} into Local Ollama...
echo ==============================================

ollama create {model_name} -f Modelfile
if %ERRORLEVEL% EQU 0 (
    echo.
    echo [SUCCESS] Model '{model_name}' is ready!
    echo Run it anytime with:
    echo     ollama run {model_name}
    echo.
) else (
    echo [ERROR] Make sure Ollama is installed from https://ollama.com and running.
)
pause
"""
